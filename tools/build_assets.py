"""Uploads all models, their textures and effect images, then writes
src/shared/Config/Assets.luau with the new IDs.

Build everything into one folder first:
    python blender/dragons.py blender/out
    python blender/eggs.py blender/out
    python blender/props.py blender/out
    python blender/effects.py blender/out
    python tools/sounds.py blender/out
Then (with ROBLOX_API_KEY and ROBLOX_USER_ID set):
    python tools/build_assets.py blender/out

Only files that changed since the last upload are uploaded again
(tracked in tools/asset_manifest.json).
"""

import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from upload_model import upload  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, "tools", "asset_manifest.json")
ASSETS_LUAU = os.path.join(ROOT, "src", "shared", "Config", "Assets.luau")

DRAGONS = ["Mossling", "Pebblewing", "Emberkit", "Reedscale", "Frostfang", "Thornback", "Magmaw", "Stormtail",
           "Solaris", "Glacius", "Voidwyrm", "Aurora", "Starborn", "ElderDragon"]
EGGS = ["EggCommon", "EggUncommon", "EggRare", "EggEpic", "EggLegendary", "EggMythic", "EggCelestial"]
PROPS = ["CastleWall", "CastleTower", "Gatehouse", "Perch", "WildNest", "FusionAltar", "TreasureChest", "LockPad",
         "Shelter", "ZoneSign", "Tablet", "Club", "PineTree", "OakTree", "Boulder", "LavaRock", "IceSpire",
         "VoidCrystal", "FlowerBush", "Mushroom"]
MODELS = DRAGONS + EGGS + PROPS
IMAGES = ["FxGlow", "FxSpark", "FxFlame", "FxSmoke", "FxStar", "FxCoin"]
# Made by tools/sounds.py (files are Sfx<Name>.wav).
SOUNDS = ["Collect", "Hatch", "NewDragon", "Grab", "Place", "Bonk", "Swing", "Roar", "Fire", "Warning", "Click",
          "Error", "Announce", "Upgrade", "Rebirth", "Alarm", "Sneak", "Lock", "Sell", "Star", "Burned"]


def sha(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def upload_if_changed(manifest, key, path, display):
    if not os.path.exists(path):
        sys.exit(f"Missing {path}. Run the Blender scripts first (see the top of this file).")
    digest = sha(path)
    entry = manifest.get(key)
    if entry and entry["sha"] == digest:
        return entry["id"]
    asset_id = upload(path, display, "Dragon Egg Heist asset")
    manifest[key] = {"sha": digest, "id": asset_id}
    with open(MANIFEST, "w") as f:
        json.dump(manifest, f, indent=2, sort_keys=True)
    print(f"uploaded {key}: {asset_id}")
    return asset_id


def main(folder):
    for var in ("ROBLOX_API_KEY", "ROBLOX_USER_ID"):
        if not os.environ.get(var):
            sys.exit(f"Set {var} first (see tools/upload_model.py).")
    manifest = {}
    if os.path.exists(MANIFEST):
        with open(MANIFEST) as f:
            manifest = json.load(f)

    models, images, sounds = {}, {}, {}
    for name in MODELS:
        model_id = upload_if_changed(manifest, name + ".fbx", os.path.join(folder, name + ".fbx"), f"DEH {name}")
        texture_id = upload_if_changed(manifest, name + ".png", os.path.join(folder, name + ".png"), f"DEH {name} texture")
        models[name] = (model_id, texture_id)
    for name in IMAGES:
        images[name] = upload_if_changed(manifest, name + ".png", os.path.join(folder, name + ".png"), f"DEH {name}")
    for name in SOUNDS:
        file = f"Sfx{name}.wav"
        sounds[name] = upload_if_changed(manifest, file, os.path.join(folder, file), f"DEH {name} sound")

    lines = [
        "-- Generated by tools/build_assets.py. Don't edit by hand; rebuild instead.",
        "-- Models: the uploaded mesh and its texture (uploaded as a Decal).",
        "-- Images: effect images (Decals). The server looks up the real image IDs",
        "-- from the Decals when it starts (see Services/AssetService).",
        "",
        "return {",
        "\tModels = {",
    ]
    for name in MODELS:
        m, t = models[name]
        lines.append(f"\t\t{name} = {{ Model = {m}, Texture = {t} }},")
    lines += ["\t},", "\tImages = {"]
    for name in IMAGES:
        lines.append(f"\t\t{name} = {images[name]},")
    lines += ["\t},", "\tSounds = {"]
    for name in SOUNDS:
        lines.append(f"\t\t{name} = {sounds[name]},")
    lines += ["\t},", "}", ""]
    with open(ASSETS_LUAU, "w") as f:
        f.write("\n".join(lines))
    print("wrote", ASSETS_LUAU)


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1])
